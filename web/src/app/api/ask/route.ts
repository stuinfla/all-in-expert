/**
 * Returns 3 representative sample quotes per core bestie, cleaned of raw
 * transcript noise (>> markers, filler text). Quotes are hand-indexed to
 * maximise voice distinctiveness: Chamath's "Look," openers + big numbers,
 * Sacks' methodical framework-building, Friedberg's science reframes,
 * Jason's hype + moderator energy.
 *
 * Hand-selected indices per bestie:
 * Chamath: "Look," opener (#23), TX data-center electricity numbers (#21), strategic assertion (#48)
 * Sacks: power/democratic-power framework (#3), censorship analysis (#27), AI deal breakdown (#25)
 * Friedberg: AI-jobs / tech-progress framing (#12), stimulus scorecard (#33), Science Corner (#37)
 * Jason: COVID/adult-responsibilities opener (#39), "greatest business ever" (#23), 8-billion minds (#40)
 */
function getSpeakerVoiceExamples(): string {
  const profiles = getSpeakerProfiles();

  const QUOTE_INDICES: Record<string, number[]> = {
    chamath: [23, 21, 48],
    sacks: [3, 27, 25],
    friedberg: [12, 33, 37],
    calacanis: [39, 23, 40],
  };

  const LABELS: Record<string, string> = {
    chamath: 'CHAMATH',
    sacks: 'SACKS',
    friedberg: 'FRIEDBERG',
    calacanis: 'JASON',
  };

  const sections: string[] = [];

  for (const [key, indices] of Object.entries(QUOTE_INDICES)) {
    const speaker = profiles[key];
    if (!speaker || !Array.isArray(speaker.sampleQuotes)) continue;
    const label = LABELS[key];
    const quotes: string[] = [];

    for (const idx of indices) {
      const q = speaker.sampleQuotes[idx];
      if (!q) continue;
      let text: string = (q.text || '').trim();
      // Strip raw interview markers (>> Name. >> or >> Name:)
      text = text.replace(/>>[\s\w]+\.?\s*/g, ' ').replace(/\s{2,}/g, ' ').trim();
      // Trim to ~280 chars at a word boundary so quotes stay snappy
      if (text.length > 280) {
        const cut = text.lastIndexOf(' ', 280);
        text = cut > 200 ? text.slice(0, cut) + '\u2026' : text.slice(0, 280) + '\u2026';
      }
      if (text.length > 40) quotes.push(`  \u2022 "${text}"`);
    }

    if (quotes.length > 0) {
      sections.push(`${label} actually says things like:\n${quotes.join('\n')}`);
    }
  }

  return sections.join('\n\n');
}

/**
 * Semantic search via precomputed embeddings binary + pure-JS cosine.
 * This is the primary search path — RVF native module doesn't boot in
 * Vercel serverless, so we ship vectors as Float32 blobs and do the
 * similarity math in plain JS. ~30ms for 15k vectors.
 */
async function semanticSearchBin(query: string, limit: number, speakerFilter?: string | null) {
  const index = await getContentIndex();
  const embeddings = getEmbeddingsBin();
  if (!embeddings) {
    console.log('[semanticSearchBin] embeddings binary not available');
    return null;
  }
  console.log(`[semanticSearchBin] loaded ${embeddings.order.length} vectors, embedding query...`);

  let queryVec: Float32Array;
  try {
    queryVec = await embedQuery(query);
    console.log(`[semanticSearchBin] query embedded, dims=${queryVec.length}`);
  } catch (err) {
    console.error('[semanticSearchBin] Query embedding failed:', err);
    return null;
  }

  const { bin, order } = embeddings;
  const N = order.length;
  // Vectors from the build script are already L2-normalized, so cosine == dot product
  const results: Array<{ id: string; entry: ContentEntry; distance: number; rawDistance: number }> = [];

  for (let i = 0; i < N; i++) {
    const offset = i * EMBEDDING_DIMS;
    let dot = 0;
    for (let j = 0; j < EMBEDDING_DIMS; j++) {
      dot += queryVec[j] * bin[offset + j];
    }
    const id = order[i];
    const entry = index[id];
    if (!entry) continue;
    // Pre-filter by speakerKey (per-turn primary speaker) when available;
    // fall back to the alias-mention array `m` for older chunks without `sk`.
    if (speakerFilter) {
      const matchesSk = entry.sk && entry.sk !== 'unknown' && entry.sk === speakerFilter;
      const matchesM  = entry.m.includes(speakerFilter);
      if (!matchesSk && !matchesM) continue;
    }
    // Convert similarity (higher = better) to distance (lower = better), apply recency
    const rawDistance = 1 - dot;
    const rec = recencyWeight(entry.v);
    results.push({ id, entry, rawDistance, distance: rawDistance / rec });
  }

  results.sort((a, b) => a.distance - b.distance);
  return results.slice(0, limit);
}

/**
 * RVF (HNSW) semantic search — try first; falls back to bin+cosine if it
 * throws (native module compat, file missing, etc). Returns null on failure.
 *
 * NOTE on ID translation: RVF v0.2 assigns internal integer labels during
 * ingest and returns those labels (not the original string IDs) on query.
 * Our build-knowledge-base.mjs ingests entries in the same order as
 * embeddings-order.json, so RVF label N maps to embeddings-order[N-1].
 * We translate before hydrating from content-index.
 */
async function semanticSearchRvf(
  query: string,
  limit: number,
  speakerFilter?: string | null
) {
  const t0 = Date.now();
  const db = await getRvf();
  if (!db) {
    console.log('[semanticSearchRvf] RVF not available');
    return null;
  }
  try {
    const index = await getContentIndex();
    const embeddings = getEmbeddingsBin();
    const order = embeddings?.order;
    if (!order || order.length === 0) {
      console.log('[semanticSearchRvf] embeddings-order not available for ID translation');
      return null;
    }
    const queryVec = await embedQuery(query);
    // Over-fetch so we have room to filter by speaker + recency-rerank
    const rvfResults = await db.query(queryVec, limit * 3, { efSearch: 250 });
    const hydrated: Array<{
      id: string; entry: ContentEntry; distance: number; rawDistance: number;
    }> = [];
    let resolved = 0;
    for (const r of rvfResults) {
      // Translate RVF integer label → string content-index key via embeddings-order
      const label = parseInt(String(r.id), 10);
      if (!Number.isFinite(label) || label < 1 || label > order.length) continue;
      const contentKey = order[label - 1];
      const entry = index[contentKey];
      if (!entry) continue;
      resolved++;
      if (speakerFilter) {
        const matchesSk = entry.sk && entry.sk !== 'unknown' && entry.sk === speakerFilter;
        const matchesM  = entry.m.includes(speakerFilter);
        if (!matchesSk && !matchesM) continue;
      }
      const rec = recencyWeight(entry.v);
      hydrated.push({
        id: contentKey,
        entry,
        rawDistance: r.distance,
        distance: r.distance / rec,
      });
    }
    hydrated.sort((a, b) => a.distance - b.distance);
    const top = hydrated.slice(0, limit);
    console.log(
      `[semanticSearchRvf] HNSW ${rvfResults.length} raw → ${resolved} resolved → ${top.length} after speaker filter in ${Date.now() - t0}ms`
    );
    return top.length > 0 ? top : null;
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    console.log(`[semanticSearchRvf] FAILED after ${Date.now() - t0}ms: ${msg}`);
    return null;
  }
}

/**
 * Semantic search: prefer RVF (HNSW) only when its index was built in the same
 * embedding space as the query model (text-embedding-3-small @ 384d). Otherwise
 * fall back to the flat binary scan over embeddings.bin (which IS rebuilt by
 * scripts/build-embeddings-openai.mjs and therefore guaranteed to match).
 *
 * Set ENABLE_RVF=1 once the RVF file has been rebuilt with OpenAI vectors.
 * Until then, querying the MiniLM-built RVF with OpenAI query vectors would
 * produce noise — exactly the bug the OpenAI re-embedding was meant to fix.
 */
async function semanticSearch(query: string, limit = 30, speakerFilter?: string | null) {
  await getContentIndex();

  // Tier 1: RVF (HNSW) — opt-in until index is rebuilt in the OpenAI vector space.
  if (process.env.ENABLE_RVF === '1') {
    const rvfResults = await semanticSearchRvf(query, limit, speakerFilter);
    if (rvfResults && rvfResults.length > 0) {
      return { results: rvfResults, mode: 'rvf' as const };
    }
  }

  // Tier 2: flat binary scan — same vector space as the query (OpenAI 384d),
  // ~30ms for 15k vectors. This is the primary semantic path until RVF is rebuilt.
  const binResults = await semanticSearchBin(query, limit, speakerFilter);
  if (binResults && binResults.length > 0) {
    return { results: binResults, mode: 'semantic' as const };
  }

  // All dense paths exhausted — return empty so hybridSearch can merge with tfidf.
  // Reported as 'empty' (not 'semantic') so downstream can distinguish a successful
  // semantic search that happened to return zero from one where every dense path failed.
  return { results: [] as Array<{ id: string; entry: ContentEntry; distance: number; rawDistance: number }>, mode: 'empty' as const };
}

// ─── BM25-Okapi sparse search (function name kept for backward compat) ────────
/**
 * BM25-Okapi (k1=1.5, b=0.75) sparse retrieval over the full content index.
 * Replaces prior TF-IDF — BM25 saturates term frequency and normalises for chunk
 * length, giving materially better idiom matching for podcast catchphrases
 * ("Best episode ever", "Science Corner", etc.) than raw TF-IDF.
 *
 * score(D,q) = sum_qi[ IDF(qi) * f(qi,D)*(k1+1) / (f(qi,D) + k1*(1-b+b*|D|/avgdl)) ]
 *
 * Separated from semanticSearch so hybridSearch() can run both in parallel.
 * Returns results sorted by distance (lower = better), same shape as semantic results.
 */
async function tfidfSearch(
  query: string,
  limit: number,
  speakerFilter?: string | null
): Promise<Array<{ id: string; entry: ContentEntry; distance: number; rawDistance: number }>> {
  const index = await getContentIndex();

  // BM25 hyperparameters (Okapi standard)
  const K1 = 1.5;
  const B  = 0.75;

  // Load IDF + doc-lengths (lazy-cached)
  const idf = getIdf();
  const docLengths = getDocLengths();
  const avgdl = (docLengths['__avgdl__'] as number) || 141.53; // fallback from build run

  // Tokenize query — same rules as build-idf.mjs (>2 chars, <30 chars)
  const queryTokens = query
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .split(/\s+/)
    .filter((w) => w.length > 2 && w.length < 30);

  // Stopwords — no retrieval signal
  const stopWords = new Set([
    'what', 'would', 'will', 'about', 'think', 'they', 'this', 'that', 'from',
    'have', 'been', 'should', 'could', 'does', 'with', 'going', 'their', 'then',
    'than', 'them', 'when', 'where', 'there', 'these', 'those', 'here', 'into',
    'just', 'like', 'over', 'some', 'such', 'take', 'very', 'much', 'each',
    'make', 'most', 'said', 'says', 'back', 'been', 'were', 'was', 'are',
    'you', 'the', 'and', 'for', 'but', 'not', 'has', 'had', 'who', 'why',
    'how', 'all', 'any', 'can', 'did', 'get', 'got', 'her', 'him', 'his',
    'its', 'let', 'out', 'see', 'she', 'too', 'two', 'use', 'way',
    'bestie', 'besties', 'show',
  ]);

  type QueryTerm = { term: string; idfScore: number; primary: boolean };
  const queryTerms: QueryTerm[] = [];
  const seenTerms = new Set<string>();

  for (const tok of queryTokens) {
    if (seenTerms.has(tok)) continue;
    seenTerms.add(tok);
    if (stopWords.has(tok)) continue;
    const termIdf = idf[tok] ?? 5.5; // unknown terms treated as rare
    queryTerms.push({ term: tok, idfScore: termIdf, primary: termIdf > 2.5 });
  }

  if (queryTerms.length === 0) return [];

  const primaryTerms = queryTerms.filter((t) => t.primary);

  const scored: Array<{ id: string; entry: ContentEntry; distance: number; rawDistance: number }> = [];

  for (const [id, entry] of Object.entries(index)) {
    if (speakerFilter) {
      const matchesSk = entry.sk && entry.sk !== 'unknown' && entry.sk === speakerFilter;
      const matchesM  = entry.m.includes(speakerFilter);
      if (!matchesSk && !matchesM) continue;
    }

    const content = entry.c.toLowerCase();

    // Fast pre-filter: at least one primary term must appear literally in the chunk
    if (primaryTerms.length > 0) {
      const hasPrimary = primaryTerms.some((pt) => content.includes(pt.term));
      if (!hasPrimary) continue;
    }

    // BM25 document length — fall back to avgdl when not in doc-lengths.json
    const dl = (docLengths[id] as number) || avgdl;
    const lenNorm = 1 - B + B * (dl / avgdl);

    let bm25Score = 0;
    for (const qt of queryTerms) {
      // Count whole-word occurrences of qt.term in content
      let f = 0;
      let pos = content.indexOf(qt.term);
      while (pos !== -1) {
        const before = pos === 0 ? ' ' : content[pos - 1];
        const after  = content[pos + qt.term.length] || ' ';
        if (!/[a-z0-9]/.test(before) && !/[a-z0-9]/.test(after)) {
          f++;
        }
        pos = content.indexOf(qt.term, pos + qt.term.length);
      }
      if (f === 0) continue;

      // BM25 term contribution
      const numerator   = f * (K1 + 1);
      const denominator = f + K1 * lenNorm;
      bm25Score += qt.idfScore * (numerator / denominator);
    }

    if (bm25Score > 0) {
      // Normalise to [0,1]: soft ceiling = sum of per-term max contribution (idf*(k1+1))
      const softCeil = queryTerms.reduce((s, t) => s + t.idfScore * (K1 + 1), 0) || 1;
      const normalized = Math.min(1, bm25Score / softCeil);
      const rawDistance = 1 - normalized;
      const rec = recencyWeight(entry.v);
      scored.push({ id, entry, rawDistance, distance: rawDistance / rec });
    }
  }

  scored.sort((a, b) => a.distance - b.distance);
  return scored.slice(0, limit);
}

// ─── Reciprocal Rank Fusion (k=60) ───────────────────────────────────────────
/**
 * Merge ranked lists from multiple retrievers via RRF.
 * score(doc) = sum_over_rankers( 1 / (k + rank_in_that_ranker) )
 * Higher RRF score = better. k=60 is the standard hyperparameter from the
 * original Cormack et al. paper — it suppresses outlier rank-1 dominance
 * while giving enough signal for top-20 documents.
 */
function rrfFuse<T extends { id: string }>(
  rankedLists: T[][],
  k = 60
): Map<string, { item: T; rrfScore: number; bestRank: number; listSize: number }> {
  const scores = new Map<string, { item: T; rrfScore: number; bestRank: number; listSize: number }>();
  for (let li = 0; li < rankedLists.length; li++) {
    const list = rankedLists[li];
    for (let rank = 0; rank < list.length; rank++) {
      const item = list[rank];
      const contribution = 1 / (k + rank + 1); // +1 so rank-0 is 1/(k+1)
      const existing = scores.get(item.id);
      if (existing) {
        existing.rrfScore += contribution;
        // Track the best (lowest) rank this item achieved across all rankers,
        // and the size of the list it achieved that rank in (for threshold math).
        if (rank < existing.bestRank) {
          existing.bestRank = rank;
          existing.listSize = list.length;
        }
      } else {
        scores.set(item.id, { item, rrfScore: contribution, bestRank: rank, listSize: list.length });
      }
    }
  }
  return scores;
}

// ─── Claim-bearing score ─────────────────────────────────────────────────────
/**
 * Score a chunk by how likely it is to contain a specific, claim-bearing
 * statement. Returns a value in [0, 0.8].
 *
 * Heuristic weights:
 *   +0.20  chunk contains any digit (numbers signal specific claims)
 *   +0.20  chunk contains $ or % (financial/quantitative claim)
 *   +0.15  opinion verb-phrase ("I think", "we should", etc.)
 *   +0.15  chunk length > 250 chars (longer → more developed argument)
 *   +0.10  non-empty, non-'unknown' speaker key (grounded attribution)
 *
 * Used in two places:
 *  1. RRF fusion: rrfScore × (1 + claimBearingScore) so claim-dense
 *     chunks rank higher before MMR.
 *  2. Post-MMR secondary swap: chunk scoring < 0.2 is swapped for an
 *     unselected candidate from same speaker scoring ≥ 0.4.
 */
function claimBearingScore(text: string, sk?: string): number {
  let score = 0;
  if (/\d/.test(text)) score += 0.20;
  if (/[$%]/.test(text)) score += 0.20;
  if (/\b(i think|we should|the problem is|the issue is|we need to|i would)\b/i.test(text)) score += 0.15;
  if (text.length > 250) score += 0.15;
  if (sk && sk !== 'unknown' && sk !== '') score += 0.10;
  return Math.min(score, 0.80);
}

// ─── Hybrid search (dense + sparse + RRF) ────────────────────────────────────
/**
 * Run semanticSearch and tfidfSearch in parallel, fuse with RRF (k=60),
 * apply recency weighting on top of RRF score, return top-limit results.
 *
 * Why k=60: standard from the RRF paper. Larger k smooths rank contributions
 * (good when retrievers disagree on rank-1); smaller k amplifies top-rank
 * winners. 60 balances precision and recall for our ~15k corpus.
 */
async function hybridSearch(
  query: string,
  limit = 30,
  speakerFilter?: string | null,
  topicalMode = false
): Promise<{ results: Array<{ id: string; entry: ContentEntry; distance: number; rawDistance: number }>; mode: 'hybrid' }> {
  // Over-fetch from each ranker so RRF has good coverage before trimming
  const fetchLimit = Math.min(limit * 3, 90);

  const [semanticResult, tfidfResults] = await Promise.all([
    semanticSearch(query, fetchLimit, speakerFilter),
    tfidfSearch(query, fetchLimit, speakerFilter),
  ]);

  const denseList = semanticResult.results;
  const sparseList = tfidfResults;

  console.log(
    `[hybridSearch] dense=${denseList.length} sparse=${sparseList.length} topical=${topicalMode}`
  );

  // If both rankers returned nothing, return empty
  if (denseList.length === 0 && sparseList.length === 0) {
    return { results: [], mode: 'hybrid' };
  }

  // RRF fusion
  const fused = rrfFuse([denseList, sparseList], 60);

  // Recency parameters depend on query type
  const halfLife = topicalMode ? 90 : 180;
  const floor = topicalMode ? 0.15 : 0.4;

  // Convert RRF scores to distance-like values for downstream compatibility.
  // Higher rrfScore → lower distance. Apply recency boost + claim-bias.
  //
  // Topical-relevance gate (iter-4 fix for q20/q07 regressions):
  // Claim-bias should only boost chunks already topically-relevant.
  // A chunk that appears only in the bottom-half of BOTH rankers is
  // likely off-topic — we cap its claim multiplier at 1.05 (near-zero boost)
  // so numeric density alone cannot rescue it. A chunk in the top-quartile
  // of EITHER ranker gets the full multiplier (up to 1.80). The threshold
  // interpolates linearly between these two cases.
  //
  // Gate logic:
  //   topHalf  = bestRank < listSize/2   → full multiplier allowed
  //   bottom-half on both rankers        → cap at 1.05
  //   top-quartile on either ranker      → full multiplier
  //
  // This prevents off-topic claim-dense chunks (e.g. Elon/Baker on tariffs)
  // from outranking on-topic less-claim-dense Sacks/Chamath chunks.
  const merged = Array.from(fused.values()).map(({ item, rrfScore, bestRank, listSize }) => {
    const rec = recencyWeight(item.entry.v, halfLife, floor);
    const rawClaimScore = claimBearingScore(item.entry.c, item.entry.sk);

    // topical gate: is this chunk in the top-half of its best ranker?
    const halfSize = listSize > 0 ? listSize / 2 : fetchLimit / 2;
    const quarterSize = listSize > 0 ? listSize / 4 : fetchLimit / 4;
    let claimCap: number;
    if (bestRank < quarterSize) {
      // Top-quartile of some ranker → topically strong, allow full claim boost
      claimCap = 1.80;
    } else if (bestRank < halfSize) {
      // Top-half but not top-quartile → moderate boost allowed
      claimCap = 1.40;
    } else {
      // Bottom-half of BOTH rankers → topically weak, minimal claim boost
      claimCap = 1.05;
    }
    const claimBias = Math.min(1 + rawClaimScore, claimCap);
    const biasedRrf = rrfScore * claimBias;
    // RRF score max ≈ 1/(k+1) + 1/(k+1) ≈ 0.032 for k=60; normalise to [0,1].
    // Distance = (1 - biasedRrf*31) gives ~0 for perfect, ~1 for irrelevant.
    const normalised = Math.min(1, biasedRrf * 31);
    const rawDistance = 1 - normalised;
    // Attach bestRank so the secondary-swap gate can check topical relevance
    return { ...item, rawDistance, distance: rawDistance / rec, rrfBestRank: bestRank, rrfListSize: listSize };
  });

  merged.sort((a, b) => a.distance - b.distance);
  return { results: merged.slice(0, limit), mode: 'hybrid' };
}

// ─── MMR diversity reranking ──────────────────────────────────────────────────
/**
 * Maximal Marginal Relevance reranking for diversity.
 * Iteratively selects the chunk that maximises:
 *   λ·sim(chunk, query) − (1−λ)·max_already_selected sim(chunk, selected_i)
 * with λ=0.7. Uses text-overlap Jaccard as a cheap similarity proxy (avoids
 * a second embedding pass). Same-episode penalty: second chunk from an
 * episode in the selected set gets a 0.5 diversity multiplier applied.
 *
 * Why λ=0.7: we weight relevance 70% vs diversity 30%. In a voice-synthesis
 * context you need the most relevant facts first; diversity is secondary.
 * λ<0.5 would produce maximally diverse but possibly tangential results.
 */
function mmrRerank(
  candidates: Array<{ id: string; entry: ContentEntry; distance: number; rawDistance: number }>,
  topK: number,
  lambda = 0.7
): Array<{ id: string; entry: ContentEntry; distance: number; rawDistance: number }> {
  if (candidates.length <= topK) return candidates;

  // Pre-compute token sets for Jaccard similarity (cheap text-overlap proxy)
  const tokenSets = candidates.map((c) => {
    const words = c.entry.c.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').split(/\s+/).filter((w) => w.length >= 3);
    return new Set(words);
  });

  // relevance(i) = 1 - distance (higher = better)
  const relevance = candidates.map((c) => Math.max(0, 1 - c.distance));

  function jaccard(a: Set<string>, b: Set<string>): number {
    if (a.size === 0 || b.size === 0) return 0;
    let inter = 0;
    for (const tok of a) if (b.has(tok)) inter++;
    return inter / (a.size + b.size - inter);
  }

  const selected: number[] = [];
  const selectedEpisodes = new Map<string, number>(); // episodeId → count
  const remaining = new Set(candidates.map((_, i) => i));

  while (selected.length < topK && remaining.size > 0) {
    let bestIdx = -1;
    let bestScore = -Infinity;

    for (const i of remaining) {
      // Max similarity to already-selected items
      let maxSim = 0;
      for (const j of selected) {
        const sim = jaccard(tokenSets[i], tokenSets[j]);
        if (sim > maxSim) maxSim = sim;
      }

      let score = lambda * relevance[i] - (1 - lambda) * maxSim;

      // Same-episode penalty: subtract a fixed amount per prior chunk from the
      // same episode. Subtraction (rather than multiplication) is required so
      // negative scores get more negative — multiplying by 0.5 would make a
      // negative score larger and accidentally REWARD same-episode duplicates.
      const SAME_EPISODE_PENALTY = 0.15;
      const sameEpCount = selectedEpisodes.get(candidates[i].entry.v) ?? 0;
      if (sameEpCount > 0) {
        score -= SAME_EPISODE_PENALTY * sameEpCount;
      }

      if (score > bestScore) {
        bestScore = score;
        bestIdx = i;
      }
    }

    if (bestIdx === -1) break;
    selected.push(bestIdx);
    remaining.delete(bestIdx);
    const ep = candidates[bestIdx].entry.v;
    selectedEpisodes.set(ep, (selectedEpisodes.get(ep) ?? 0) + 1);
  }

  return selected.map((i) => candidates[i]);
}

