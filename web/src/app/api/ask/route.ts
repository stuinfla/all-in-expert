/**
 * Fair-use citation truncation. Caps verbatim transcript quotes at QUOTE_MAX_CHARS
 * to keep the per-citation excerpt short enough to qualify as fair-use commentary
 * rather than substantial reproduction. When the source chunk is longer, we prefer
 * the first sentence containing the query's highest-IDF (most distinctive) token —
 * that's usually the most relevant sentence to cite. Falls back to first 280 chars
 * with an ellipsis when no IDF-anchored sentence fits in the budget.
 */
const QUOTE_MAX_CHARS = 280;
function truncateQuoteForFairUse(chunk: string, query: string): string {
  if (!chunk) return '';
  if (chunk.length <= QUOTE_MAX_CHARS) return chunk;

  // Split into sentences on . ? ! followed by space/end. Keep the punctuation.
  const sentences = chunk.match(/[^.!?]+[.!?]+(\s|$)|[^.!?]+$/g) ?? [chunk];

  // Pick the highest-IDF query token (rarer = more distinctive).
  const idf = getIdf();
  const queryTokens = query
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .split(/\s+/)
    .filter((t) => t.length >= 3);
  let topToken: string | null = null;
  let topIdf = -Infinity;
  for (const t of queryTokens) {
    const score = idf[t] ?? 5.5;
    if (score > topIdf) {
      topIdf = score;
      topToken = t;
    }
  }

  if (topToken) {
    const needle = topToken;
    for (const s of sentences) {
      if (s.toLowerCase().includes(needle) && s.trim().length <= QUOTE_MAX_CHARS) {
        return s.trim();
      }
    }
  }

  return chunk.slice(0, QUOTE_MAX_CHARS - 1).trimEnd() + '…';
}

/**
 * Compute a recency weight multiplier for a given episode date.
 * Recent episodes get full weight (1.0); old episodes decay to a floor.
 *
 * @param videoId   Episode video ID to look up date for.
 * @param halfLife  Decay half-life in days (default 180 for biographical/factual).
 *                  Pass 90 for topical/opinion queries (tighter recency).
 * @param floor     Minimum weight floor (default 0.4).
 *                  Pass 0.15 for topical/opinion queries.
 */
function recencyWeight(videoId: string, halfLife = 180, floor = 0.4): number {
  const dates = getEpisodeDates();
  const dateStr = dates[videoId];
  if (!dateStr) return 0.85; // unknown date → slight penalty vs known-recent
  const episodeMs = new Date(dateStr).getTime();
  const ageDays = (Date.now() - episodeMs) / (1000 * 60 * 60 * 24);
  if (ageDays < 0) return 1.0;
  // Exponential decay with configurable half-life, floored
  return Math.max(floor, floor + (1 - floor) * Math.exp(-ageDays / halfLife));
}



